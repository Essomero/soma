#!/usr/bin/env tsx
/**
 * Build-time export: seed corpus -> api/_corpus.js (gitignored).
 * The bundled snapshot lets a running deployment self-heal an empty
 * store on first request (see ensureSeeded in api/content.js) with no
 * CLI step and no rebuild. Plain .js output: zero import interop risk.
 * Run: part of `npm run build`, before seed --if-empty.
 */
import { writeFileSync } from "fs";
import { join, dirname } from "path";
import { fileURLToPath } from "url";
import { loadCorpus } from "./corpus.ts";

const outPath = join(dirname(fileURLToPath(import.meta.url)), "..", "api", "_corpus.js");

const corpus = loadCorpus();
const payload = JSON.stringify(corpus);
writeFileSync(
  outPath,
  `// GENERATED by scripts/export-corpus.ts at build time — do not edit.\n` +
  `// Versioned source: src/content/**/*.ts via scripts/corpus.ts.\n` +
  `export const CORPUS_JSON = ${JSON.stringify(payload)};\n`
);
console.log(`corpus export: ${corpus.length} rows -> api/_corpus.js`);
